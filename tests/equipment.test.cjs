const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const THREE=require('../vendor/three.min.js');
const root={THREE};root.window=root;vm.createContext(root);
for(const file of ['core','loot','equipment','hero-art','character-rig','flame-guardian','appearance'])vm.runInContext(fs.readFileSync(path.join(__dirname,'../js',file+'.js'),'utf8'),root);
test('armor has five compatible slots, starter items and safe save restoration',()=>{
 const s=root.RPG.fresh('ranger');
 const slots=Object.keys(root.EmberEquipment.slots);
 assert.equal(slots.length,5);
 root.EmberEquipment.clean(s);
 assert.ok(s.armorOwned.includes('wanderer_chest'));
 assert.ok(s.armorOwned.includes('wanderer_boots'));
 assert.equal(root.EmberEquipment.equip(s,'ember_chest'),false);
 assert.equal(root.EmberEquipment.equip(s,'wanderer_chest'),true);
 assert.equal(s.armorEquipped.chest,'wanderer_chest');
 const copy=root.RPG.restore(JSON.stringify(s));
 assert.equal(copy.armorEquipped.chest,'wanderer_chest');
 assert.equal(copy.classId,'ranger');
 const unsafe=root.RPG.restore(JSON.stringify({...s,armorOwned:['ember_chest','unknown','unknown','wanderer_boots'],armorEquipped:{head:'ember_chest',chest:'unknown',feet:'wanderer_boots',bad:'ember_chest'}}));
 assert.equal(unsafe.armorEquipped.head,null);
 assert.equal(unsafe.armorEquipped.chest,null);
 assert.equal(unsafe.armorEquipped.feet,'wanderer_boots');
 assert.ok(!unsafe.armorOwned.includes('unknown'));
 assert.ok(!('bad' in unsafe.armorEquipped));
});
test('buy, equip and remove armor gives bounded one-time stat bonuses',()=>{
 const s=root.RPG.fresh();
 root.EmberEquipment.clean(s);
 const initialHP=root.RPG.maxHp(s),initialDamage=root.RPG.damage(s);
 assert.equal(root.EmberEquipment.equip(s,'wanderer_chest'),true);
 assert.equal(root.RPG.maxHp(s),initialHP+10);
 assert.equal(root.EmberEquipment.equip(s,'wanderer_chest'),true);
 assert.equal(root.RPG.maxHp(s),initialHP);
 assert.equal(root.EmberEquipment.buy(s,'ember_gloves'),false);
 s.gold=100;
 assert.equal(root.EmberEquipment.buy(s,'ember_gloves'),true);
 assert.equal(s.gold,5);
 assert.equal(root.EmberEquipment.buy(s,'ember_gloves'),false);
 assert.equal(root.EmberEquipment.equip(s,'ember_gloves'),true);
 assert.equal(root.RPG.damage(s),initialDamage+4);
 assert.equal(root.EmberEquipment.bonuses(s).power,4);
 const fake={...s,armorEquipped:{hands:'ember_gloves',chest:'ember_chest'},armorOwned:['wanderer_chest']};
 assert.equal(root.EmberEquipment.bonuses(fake).power,0);
 assert.equal(root.EmberEquipment.bonuses(fake).hp,0);
});
test('quest rewards unlock once and legacy accomplishments are honored',()=>{
 const s=root.RPG.fresh();
 s.chest=true;s.bowQuest=2;s.kills=['boss','rootboss'];s.shrineBlessing=true;s.sideQuest=3;s.dungeon=3;
 const first=root.EmberEquipment.syncRewards(s);
 assert.equal(first.length,7);
 assert.equal(root.EmberEquipment.syncRewards(s).length,0);
 assert.equal(new Set(s.armorOwned).size,s.armorOwned.length);
 const saved=root.RPG.restore(JSON.stringify(s));
 assert.equal(root.EmberEquipment.syncRewards(saved).length,0);
 assert.ok(saved.armorOwned.includes('ember_chest'));
});
test('equipped pieces render visibly on correct Three.js bone joints',()=>{
 const rig=root.EmberCharacterRig.create(THREE);
 const view=root.EmberEquipment.attach(THREE,rig);
 const s=root.RPG.fresh();root.EmberEquipment.clean(s);
 for(const id of ['wanderer_chest','wanderer_boots'])root.EmberEquipment.equip(s,id);
 view.sync(s);
 assert.ok(view.groups.wanderer_chest.userData.meshes.every(m=>m.visible));
 assert.ok(view.groups.wanderer_boots.userData.meshes.every(m=>m.visible));
 const chest=view.groups.wanderer_chest.userData.meshes[0];
 const boot=view.groups.wanderer_boots.userData.meshes[0];
 assert.strictEqual(chest.parent,rig.joints.chest);
 assert.strictEqual(boot.parent,rig.joints.foot_l);
 assert.strictEqual(rig.blade.parent,rig.joints.weapon_r);
 rig.group.updateMatrixWorld(true);const vertex=new THREE.Vector3().fromBufferAttribute(boot.geometry.attributes.position,0);
 const before=boot.localToWorld(vertex.clone());
 rig.joints.foot_l.rotation.x=.7;rig.group.updateMatrixWorld(true);
 const after=boot.localToWorld(vertex.clone());
 assert.ok(before.distanceTo(after)>.01);
 root.EmberEquipment.equip(s,'wanderer_chest');view.sync(s);
 assert.ok(view.groups.wanderer_chest.userData.meshes.every(m=>!m.visible));
});
